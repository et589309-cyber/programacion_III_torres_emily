// Variables con let
let marca = 'Toyota';
let modelo = 'Corolla';
let precio = 18500;

console.log(marca);
console.log(modelo);
console.log(precio);

// Cambiar el valor de una variable
precio = 17000;
console.log('Nuevo precio:', precio);

// Variable con const (no cambia)
const concesionaria = 'AutoDrive';
console.log('Concesionaria:', concesionaria);

// Variable con var
var color = 'Rojo';
console.log('Color:', color);
